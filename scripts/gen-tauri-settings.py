#!/usr/bin/env python3
"""Generate apps/app/gen/android/tauri.settings.gradle.

Tauri's Gradle Rust plugin writes this file during `tauri android build`, so it is
never committed (the contents embed absolute paths into the cargo registry).
CI builds assemble the APK without that plugin, so the file has to be produced
here: every project referenced by app/tauri.build.gradle.kts must point at the
matching crate's android module inside the local cargo registry.
"""

import json
import os
import re
import subprocess
import sys

GENERATED = "// THIS FILE IS AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY."


def repo_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def project_dirs(root: str) -> dict[str, str]:
    """Map Gradle project name -> source directory of its android module."""
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1"],
            cwd=root,
            stderr=subprocess.DEVNULL,
        )
    )

    # Cargo package name -> directory containing its Cargo.toml
    package_dirs = {
        pkg["name"]: os.path.dirname(pkg["manifest_path"]) for pkg in metadata["packages"]
    }

    build_script = os.path.join(
        root, "apps", "app", "gen", "android", "app", "tauri.build.gradle.kts"
    )
    referenced = re.findall(r'project\(":([^"]+)"\)', open(build_script).read())

    result: dict[str, str] = {}
    for project in referenced:
        # :tauri-android lives in tauri/mobile/android, plugins in <crate>/android
        if project == "tauri-android":
            crate, subdir = "tauri", "mobile/android"
        elif project.startswith("tauri-plugin-"):
            crate, subdir = project, "android"
        else:
            continue

        crate_dir = package_dirs.get(crate)
        if not crate_dir:
            sys.exit(f"cargo metadata has no package named {crate!r}")
        android_dir = os.path.join(crate_dir, subdir)
        if not os.path.isdir(android_dir):
            sys.exit(f"{project}: {android_dir} does not exist")
        result[project] = android_dir

    return result


def main() -> None:
    root = repo_root()
    out_path = os.path.join(root, "apps", "app", "gen", "android", "tauri.settings.gradle")

    lines = [GENERATED]
    for project, directory in project_dirs(root).items():
        lines.append(f"include ':{project}'")
        lines.append(f"project(':{project}').projectDir = new File(\"{directory}\")")

    with open(out_path, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
